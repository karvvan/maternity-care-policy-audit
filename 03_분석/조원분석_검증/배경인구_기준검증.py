tot_below = (mv['인구수(명)'] < 36588).sum()
fem_below = (mv['가임여성수'] < 36588).sum()
print(f"전국 250 시군구 중 36,588 미만: 총인구 기준 {tot_below}곳 / 가임여성 기준 {fem_below}곳")
print("(지침: '배경인구가 적은 도농복합시·군은 총 105개' — 어느 해석이 105에 가까운가)")

# 도농복합시·군만으로 한정하면? (광역시 자치구·특별시 제외 근사: 시군구명이 '구'로 끝나지 않는 곳)
mask_nongu = ~mv['시군구명'].str.endswith('구')
print(f"자치구 제외 {mask_nongu.sum()}곳 중 가임여성<36,588: {(mask_nongu & (mv['가임여성수']<36588)).sum()}곳 / 총인구<36,588: {(mask_nongu & (mv['인구수(명)']<36588)).sum()}곳")

